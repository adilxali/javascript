const numbers = [1, 2, 3, 4, 5];
console.log(numbers.push(6));//always returns the new length of the array 
console.log(numbers.pop());//removes the last element of the array and returns that element

console.log(numbers.unshift(10));//always returns the new length of the array 
console.log(numbers.shift());//removes the first element of the array and returns that element